// ---- Access helpers (stand-in for the future Supabase query layer) ----

export function getAllProperties(): Property[] {
  return PROPERTIES;
}

export function getPropertyBySlug(slug: string): Property | undefined {
  return PROPERTIES.find((p) => p.slug === slug);
}

export function getFeatured(limit = 6): Property[] {
  return [...PROPERTIES]
    .filter((p) => p.boostTier)
    .sort((a, b) => (a.boostTier === "spotlight" ? -1 : 1) - (b.boostTier === "spotlight" ? -1 : 1))
    .slice(0, limit);
}

/** Most-engaged active listings (views + saves), excluding any given ids. */
export function getTrending(limit = 6, excludeIds: string[] = []): Property[] {
  const exclude = new Set(excludeIds);
  return [...PROPERTIES]
    .filter((p) => p.status === "active" && !exclude.has(p.id))
    .sort((a, b) => b.viewCount + b.saveCount * 4 - (a.viewCount + a.saveCount * 4))
    .slice(0, limit);
}

export function getSimilar(property: Property, limit = 3): Property[] {
  return PROPERTIES.filter(
    (p) =>
      p.id !== property.id &&
      (p.area === property.area || p.type === property.type) &&
      p.intent === property.intent,
  )
    .sort((a, b) => Math.abs(a.price - property.price) - Math.abs(b.price - property.price))
    .slice(0, limit);
}
